def build_trace(pr, t_rd_str, counts):
    """[(time, activity)] of a PR by the rules in the module docstring; counts accumulates what is left out."""
    tm = prep.typename_map(pr)

    def cls(w):
        return participant_class(w, tm.get(w))

    author = login_of(pr)
    created = parse_dt(pr.get("createdAt"))
    merged = parse_dt(pr.get("mergedAt"))
    ev = [(created, "open"), (merged, "merge")]
    for c in (pr.get("commits") or {}).get("nodes") or []:
        t = parse_dt(((c or {}).get("commit") or {}).get("authoredDate"))
        if t and created < t <= merged:
            ev.append((t, "revision"))
        else:
            counts["commit_outside_open_merge"] += 1
    for r in (pr.get("reviews") or {}).get("nodes") or []:
        w = login_of(r)
        if w == author:
            continue
        t = parse_dt((r or {}).get("submittedAt"))
        if not t:
            continue
        c = cls(w)
        st = (r or {}).get("state")
        if c == "human":
            if st in REVIEW_ACT:
                ev.append((t, REVIEW_ACT[st]))
            else:
                counts[f"human_review_{st}"] += 1
        elif c == "ai_assistant":
            ev.append((t, "ai"))
        else:
            counts[f"review_{c}"] += 1
    for th in (pr.get("reviewThreads") or {}).get("nodes") or []:
        for cm in (((th or {}).get("comments") or {}).get("nodes") or []):
            w = login_of(cm)
            t = parse_dt((cm or {}).get("createdAt"))
            if w == author or not t:
                continue
            c = cls(w)
            if c == "ai_assistant":
                ev.append((t, "ai"))
            else:
                counts[f"thread_comment_{c}"] += 1
    # timer: a gap longer than Delta in the trace of human activity and revisions from t_rd
    t_rd = parse_dt(t_rd_str) or created
    act = prep.activity_trace_from(pr, lambda w: cls(w) == "human", t_rd)
    for a, b in zip(act or [], (act or [])[1:]):
        if (b - a).total_seconds() > DELTA_DAYS * 86400:
            ev.append((a + timedelta(days=DELTA_DAYS), "timer"))
    ev = [(t.astimezone(timezone.utc), a) for t, a in ev]
    ev.sort(key=lambda e: (e[0], ORDER[e[1]]))
    out = []
    for t, a in ev:
        if a == "ai" and out and out[-1][1] == "ai":
            counts["ai_collapsed"] += 1
            continue
        out.append((t, a))
    return out


def drop_repeat_approvals(evs):
    """Log of the main_noreapprove variant: without a rev_approve preceded in the PR by a
    human approval with no revision in between. Returns (trace, number dropped)."""
    out, dropped, approved = [], 0, False
    for t, a in evs:
        if a == "rev_approve":
            if approved:
                dropped += 1
                continue
            approved = True
        elif a == "revision":
            approved = False
        out.append((t, a))
    return out, dropped


