def load_main(repos_filter=None):
    """repo -> {pr_number: t_rd} for the main sample (hait_filter = 1, in_main = 1)."""
    out = defaultdict(dict)
    with open(PR_TABLE, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["in_main"] == "1" and r["hait_filter"] == "1":
                if repos_filter and r["repo"] not in repos_filter:
                    continue
                out[r["repo"]][int(r["pr_number"])] = r["t_rd"]
    return out


def sample_repo(repo, numbers, n):
    """Up to n random PR numbers; the generator depends only on the seed and the repository name."""
    nums = sorted(numbers)
    rng = random.Random(f"{SEED}:{repo}")
    return sorted(rng.sample(nums, n)) if len(nums) > n else nums


def iter_selected(repo, wanted):
    """First occurrence of each selected PR in prs.jsonl (as r2_raw_v2: seen)."""
    path = os.path.join(RAW_V2, repo.replace("/", "_", 1), "prs.jsonl")
    left = set(wanted)
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = NUM_RE.search(line[:400])
            if not m or int(m.group(1)) not in left:
                continue
            pr = json.loads(line)
            num = int(pr["number"])
            if num in left:
                left.discard(num)
                yield pr
            if not left:
                return


