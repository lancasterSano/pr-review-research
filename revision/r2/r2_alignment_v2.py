def ablation(cases):
    """What lowers main precision: the same net without single fragments of the diagram.
    Without the CI loop, a revision is possible only as "Rework the change"; the timer
    and the assistant are removed from both the net and the log."""
    out = {}
    for name, (drop_tr, drop_act) in ABLATIONS.items():
        net, im, fm = build_net()
        for t in [t for t in net.transitions if t.name in drop_tr]:
            petri_utils.remove_transition(net, t)
        sub = [(c, [(t, a) for t, a in ev if a not in drop_act]) for c, ev in cases]
        log = to_event_log(sub)
        t0 = time.time()
        res = align(log, net, im, fm)
        fit = [r["fitness"] for r in res]
        prec = pm4py.precision_alignments(log, net, im, fm, multi_processing=False)
        out[name] = {"fitness": sum(fit) / len(fit),
                     "fit_pct": 100.0 * sum(1 for f in fit if f == 1.0) / len(fit),
                     "precision": prec, "seconds": round(time.time() - t0, 1)}
        print(f"ablation {name}: fitness {out[name]['fitness']:.4f}, "
              f"precision {prec:.4f}", flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repos", help="trial run: comma-separated repositories")
    ap.add_argument("--n", type=int, default=N_PER_REPO)
    ap.add_argument("--no-precision", action="store_true")
    ap.add_argument("--ablation", action="store_true",
                    help="precision diagnostics of main: net without the CI loop, timer and assistant")
    ap.add_argument("--pr-table", default=PR_TABLE, help="another PR table (read only)")
    args = ap.parse_args()
    set_pr_table(args.pr_table)
    trial = bool(args.repos) or args.n != N_PER_REPO
    out_dir = OUT + ("_trial" if trial else "")
    os.makedirs(out_dir, exist_ok=True)
    t_start = time.time()
    started = datetime.now().astimezone()

    main_rows = load_main(set(args.repos.split(",")) if args.repos else None)
    repos = sorted(main_rows)
    counts = Counter()
    cases, repo_of, sample_sizes = [], [], {}
    for repo in repos:
        nums = sample_repo(repo, main_rows[repo].keys(), args.n)
        sample_sizes[repo] = {"main_n": len(main_rows[repo]), "sampled": len(nums)}
        got = 0
        for pr in iter_selected(repo, nums):
            num = int(pr["number"])
            evs = build_trace(pr, main_rows[repo][num], counts)
            cases.append((f"{repo}#{num}", evs))
            repo_of.append(repo)
            got += 1
        if got != len(nums):
            raise SystemExit(f"{repo}: found {got} of {len(nums)} PRs in prs.jsonl")
        print(f"traces {repo}: {got}", flush=True)
    t_log = time.time()
    log = to_event_log(cases)
    acts = Counter(a for _, evs in cases for _, a in evs)
    n_events = sum(acts.values())
    print(f"log: {len(cases)} traces, {n_events} events, {t_log - t_start:.0f} s", flush=True)

    result = {"align": {
        "seed": SEED, "n_per_repo": args.n, "delta_days": DELTA_DAYS,
        "n_repos": len(repos), "n_traces": len(cases), "n_events": n_events,
        "events_by_activity": dict(sorted(acts.items())),
        "excluded_counts": dict(sorted(counts.items())),
        "n_variants": len({tuple(a for _, a in evs) for _, evs in cases}),
        "repos_below_n": {r: s["sampled"] for r, s in sample_sizes.items() if s["sampled"] < args.n},
        "sample_sizes": sample_sizes,
    }}
    A = result["align"]
    per_trace = {cid: {"repo": r, "n_events": len(evs),
                       "trace": " ".join(a for _, a in evs)} for (cid, evs), r in zip(cases, repo_of)}

    # log of the main_noreapprove variant: without repeated approvals
    cases_nr, n_dropped, n_tr_dropped = [], 0, 0
    for cid, evs in cases:
        f_evs, d = drop_repeat_approvals(evs)
        cases_nr.append((cid, f_evs))
        per_trace[cid]["nr_dropped"] = d
        n_dropped += d
        n_tr_dropped += int(d > 0)
    log_nr = to_event_log(cases_nr)
    A["noreapprove_filter"] = {
        "dropped_n": n_dropped, "dropped_pct": 100.0 * n_dropped / n_events,
        "dropped_of_approvals_pct": 100.0 * n_dropped / acts["rev_approve"] if acts["rev_approve"] else None,
        "traces_n": n_tr_dropped, "traces_pct": 100.0 * n_tr_dropped / len(cases),
        "n_events": n_events - n_dropped,
        "n_variants": len({tuple(a for _, a in evs) for _, evs in cases_nr}),
    }
    print(f"main_noreapprove: dropped {n_dropped} events ({A['noreapprove_filter']['dropped_pct']:.2f} %) "
          f"in {n_tr_dropped} traces", flush=True)
    logs = {"main": (log, cases), "relaxed": (log, cases), "main_noreapprove": (log_nr, cases_nr)}

    for variant in ("main", "relaxed", "main_noreapprove"):
        log_v, cases_v = logs[variant]
        net, im, fm = build_net(relaxed=(variant == "relaxed"))
        t0 = time.time()
        sound = pm4py.check_soundness(net, im, fm)[0]
        # translation check: traces generated by the net fit it perfectly
        from pm4py.algo.simulation.playout.petri_net import algorithm as playout
        random.seed(SEED)  # basic playout uses the global random
        sim = playout.apply(net, im, final_marking=fm,
                            parameters={"noTraces": N_PLAYOUT, "maxTraceLength": 40,
                                        "add_only_if_fm_is_reached": True})
        sim_res = align(sim, net, im, fm)
        sim_fit = sum(r["fitness"] for r in sim_res) / len(sim_res)
        t1 = time.time()
        res = align(log_v, net, im, fm)
        t2 = time.time()
        s = summarise(res, repo_of)
        lm, mm = Counter(), Counter()
        for (cid, evs), r in zip(cases_v, res):
            l1, m1 = deviations([a for _, a in evs], r["alignment"])
            lm.update(l1)
            mm.update(m1)
            per_trace[cid][f"{variant}_fitness"] = round(r["fitness"], 6)
            per_trace[cid][f"{variant}_cost"] = r["cost"] // 10000
        prec = None
        if not args.no_precision:
            prec = pm4py.precision_alignments(log_v, net, im, fm, multi_processing=False)
        t3 = time.time()
        if variant == "main_noreapprove":
            s["categories"] = categorise(cases_v, res, load_replay([c for c, _ in cases_v]),
                                         per_trace)
        s.update({
            "precision": prec, "sound": bool(sound),
            "control_playout_n": len(sim), "control_playout_fitness": sim_fit,
            "n_places": len(net.places), "n_transitions": len(net.transitions),
            "log_moves": {f"{a}|{w}": n for (a, w), n in lm.most_common()},
            "log_moves_total": sum(lm.values()),
            "model_moves": dict(mm.most_common()),
            "model_moves_total": sum(mm.values()),
            "seconds": {"control": round(t1 - t0, 1), "alignments": round(t2 - t1, 1),
                        "precision": round(t3 - t2, 1)},
        })
        A[variant] = s
        print(f"{variant}: fitness {s['fitness']:.4f}, fitting {s['fit_pct']:.1f} %, "
              f"precision {prec}, alignments {t2 - t1:.0f} s, precision {t3 - t2:.0f} s, "
              f"control {sim_fit:.4f}, sound {sound}", flush=True)

    # effect of the relaxation (transition 11): the share of non-fitting main traces that
    # fit in relaxed, and the share of main deviation cost it removes
    mc = [r["main_cost"] for r in per_trace.values()]
    rc = [r["relaxed_cost"] for r in per_trace.values()]
    bad = [i for i, c in enumerate(mc) if c > 0]
    A["relax_effect"] = {
        "main_nonfit_n": len(bad),
        "fixed_by_relaxed_n": sum(1 for i in bad if rc[i] == 0),
        "fixed_by_relaxed_pct": 100.0 * sum(1 for i in bad if rc[i] == 0) / len(bad) if bad else None,
        "main_cost_total": sum(mc), "relaxed_cost_total": sum(rc),
        "cost_removed_pct": 100.0 * (1 - sum(rc) / sum(mc)) if sum(mc) else None,
    }
    # effect of dropping repeated approvals from the log (the same main net)
    nc = [r["main_noreapprove_cost"] for r in per_trace.values()]
    A["noreapprove_effect"] = {
        "main_nonfit_n": len(bad),
        "fixed_n": sum(1 for i in bad if nc[i] == 0),
        "fixed_pct": 100.0 * sum(1 for i in bad if nc[i] == 0) / len(bad) if bad else None,
        "main_cost_total": sum(mc), "noreapprove_cost_total": sum(nc),
        # the filter can also make a trace worse: a second approval without a revision
        # "absorbed" reviews between approvals (the alignment used it instead of the first)
        "worse_n": sum(1 for a, b in zip(mc, nc) if b > a),
        "better_n": sum(1 for a, b in zip(mc, nc) if b < a),
        "became_nonfit_n": sum(1 for a, b in zip(mc, nc) if a == 0 and b > 0),
        "cost_removed_pct": 100.0 * (1 - sum(nc) / sum(mc)) if sum(mc) else None,
    }
    if args.ablation:
        A["ablation"] = ablation(cases)
    with open(PR_TABLE, "rb") as f:
        table_sha = hashlib.sha256(f.read()).hexdigest()
    A["meta"] = {
        "script": "revision/r2/r2_alignment_v2.py",
        "started": started.isoformat(timespec="seconds"),
        "runtime_seconds": round(time.time() - t_start, 1),
        "pr_table": PR_TABLE.replace(os.path.expanduser("~"), "~"),
        "pr_table_sha256": table_sha,
        "pr_table_mtime": datetime.fromtimestamp(os.path.getmtime(PR_TABLE)).isoformat(timespec="seconds"),
        "pm4py": pm4py.__version__, "python": sys.version.split()[0],
    }
    with open(os.path.join(out_dir, "r2_alignment_v2.json"), "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=1)
    fields = ["case", "repo", "n_events", "main_fitness", "main_cost", "relaxed_fitness",
              "relaxed_cost", "nr_dropped", "main_noreapprove_fitness", "main_noreapprove_cost",
              "nr_cats", "trace"]
    with open(os.path.join(out_dir, "r2_alignment_v2_traces.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fields)
        w.writeheader()
        for cid, row in per_trace.items():
            w.writerow({"case": cid, **row})
    print(f"done: {time.time() - t_start:.0f} s -> {out_dir}", flush=True)


if __name__ == "__main__":
    main()
