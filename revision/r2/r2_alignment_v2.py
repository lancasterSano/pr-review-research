#!/usr/bin/env python3
"""Chapter 2, corpus v2: checking the process projection (BPMN) by alignments.

What it computes (appendix B.2, the paragraph on comparing the process
projection with the event log by alignments). For each repository of the main
sample, up to 200 random merged PRs are taken (fixed seed; a repository's sample
does not depend on the other repositories), an event log is built from them, and
the traces are aligned with a workflow net into which the chapter 2 BPMN
diagram (bpmn_process_ua) was translated by hand. Two net variants:

  main     the diagram as is: the conditional assistant branch ("Does an
           assistant review the PR?") and repeated assistant runs (the
           simplification named in section 2.2.3);
  relaxed  the same plus "approve", "request changes" and "comment" reviews and
           revisions after the first approval (automaton transition 11,
           transition table).

A third variant (used by experiment E1 of chapter 4):

  main_noreapprove  net main, log without repeated approvals. A human rev_approve
           event is dropped if another human rev_approve preceded it in the PR
           with no revision (revision) in between: the model is already in the
           "Approved" state, and a second approval does not change it. An
           approval after rework stays (under the literal HAIT iteration rule it
           opens a new iteration); rev_changes and rev_comment always stay. The
           same 8 000 traces; the number of dropped events is reported (key
           align.noreapprove_filter). For non-fitting traces the deviations (log
           moves and visible model moves) are classified (key
           main_noreapprove.categories; exact rules in classify_moves):
             a  rev_changes or rev_comment after the first approval (together with
                the rev_approve/merge moves by which the alignment "moves" the
                approval past them);
             b  rev_approve in a trace with two or more approvals (after the
                filter, an approval after rework after an approval);
             c  all deviations of a trace with no human approval before the merge
                (a trace the state automaton rejects; checked against accepted in
                v2/r2_pr_extra_v2.csv, output of r2_raw_v2.py);
             e  a change request with no revision before the next verdict (a
                category found in the data);
             d  others (with detail by move type, event and context).
           The share of non-fitting traces whose deviations all belong to a-c is
           explained_pct (to a-c and e: explained_abce_pct).

For each variant: average trace fitness (pm4py), the share of perfectly fitting
traces, log fitness and precision (ETC over alignments) on the whole log; per
repository, fitness and the share of fitting traces; the most frequent
deviations (log moves and model moves by event type; for log moves of reviews
and revisions, separately those after the first human approval; the share of
non-fitting main traces that the relaxed variant makes fitting). Translation
check: traces generated by the net itself have fitness 1.000 (only traces that
reached the final marking within 40 visible events are taken). The net is
checked by Woflan (soundness).

Translation of the diagram (hidden transitions have no label):
  open           PR opened + parallel split gateway (4 tokens: review,
                 assistant, CI, staleness watch);
  review         Assign reviewers (hidden) -> Inspect the change -> Verdict:
                 rev_approve ends the "Approved" subprocess, rev_changes leads to
                 "Rework the change" (revision) and back to inspection,
                 rev_comment returns to inspection;
  assistant      "Does an assistant review the PR?": no (hidden) or yes -> ai,
                 with repeated ai (hidden back transition), end of the branch;
  CI             "Run CI checks" and the gateway are hidden; "Fix the change" =
                 revision and a repeated check;
  staleness      timer of an event subprocess with a single active instance:
                 timer, then a hidden "activity resumed"/"watch ended" transition;
                 the "decision to close" branch is not translated: all traces
                 are merged;
  merge          parallel join gateway (approved + CI passed) + Merge;
  end            a hidden transition collects the merge, assistant and watch
                 tokens.

Log (case = PR). Account classes and events are the same as in r2_raw_v2.py
(collector functions from revision/, unchanged):
  open         PullRequest.createdAt;
  revision     a commit with authoredDate in (createdAt, mergedAt] (as
               review_iterations);
  rev_approve, rev_changes, rev_comment
               human reviews (participant_class == 'human'), not by the author,
               by state APPROVED / CHANGES_REQUESTED / COMMENTED; DISMISSED and
               PENDING are left out (the verdict of a dismissed review is
               unknown), their count is reported;
  ai           reviews and thread comments by ai_assistant accounts, not the
               author; consecutive ai events are collapsed into one (one
               assistant run);
  timer        inserted 30 days after the start of every gap longer than
               Delta = 30 days in the trace of human activity and revisions from
               t_rd to merge (r3_v2_prep.activity_trace_from, as in the rest of
               the chapter);
  merge        PullRequest.mergedAt.
Left out (no BPMN element): human thread comments, leaving draft, review
requests, other bots' events, general conversation comments (IssueComment).
Simultaneous events are ordered: open, reviews, revision, ai, timer, merge.

Inputs (read only):
  $R3_ROOT/v2/pr_table_v2.csv  chapter 3 PR table (default
                               revision/output/r3_b40d; main sample
                               hait_filter == 1 and in_main == 1; repositories
                               come from the table, not from a list in the code);
                               another file can be given with --pr-table;
  $R3_RAW_V2/<owner>_<repo>/prs.jsonl  corpus v2 raw data (default data/raw_v2);
  $R2_DIR/v2/r2_pr_extra_v2.csv        output of r2_raw_v2.py (run it first).

Output in $R2_DIR/v2/ (default revision/output/r2/v2, git-ignored):
  r2_alignment_v2.json        summary and per-repository values (key "align");
  r2_alignment_v2_traces.csv  trace level.

Run from the repository root, in a separate environment with pm4py and pandas
(pm4py 2.7.23.7, Python 3.9.6 for the published numbers):
  PYTHONDONTWRITEBYTECODE=1 nice -n 10 <venv-with-pm4py>/bin/python \\
      revision/r2/r2_alignment_v2.py
A full run on 40 repositories takes about 20 minutes (one process). The
--ablation flag adds a diagnosis of main precision (net without the CI loop,
without the timer, without the assistant; key align.ablation), about 15 more
minutes. Trial run on a subset of repositories (output to $R2_DIR/v2_trial):
  ... r2_alignment_v2.py --repos vitejs/vite,django/django --n 50
"""
