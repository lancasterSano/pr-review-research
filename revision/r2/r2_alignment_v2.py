def to_event_log(cases):
    log = EventLog()
    for cid, evs in cases:
        tr = Trace(attributes={"concept:name": cid})
        for t, a in evs:
            tr.append(Event({"concept:name": a, "time:timestamp": t}))
        log.append(tr)
    return log


# ── workflow net from the BPMN diagram ──────────────────────────────────────

def build_net(relaxed=False):
    net = PetriNet("bpmn_process_ua" + ("_relaxed" if relaxed else ""))
    P = {}
    for name in ("source", "p_rev", "p_insp", "p_rework", "p_rev_done", "p_ai", "p_ai_run",
                 "p_ai_done", "p_ai_end", "p_ci", "p_ci_gw", "p_fix", "p_ci_ok", "p_watch",
                 "p_stale", "p_merged", "sink"):
        P[name] = PetriNet.Place(name)
        net.places.add(P[name])

    def tr(name, label, pre, post):
        t = PetriNet.Transition(name, label)
        net.transitions.add(t)
        for p in pre:
            petri_utils.add_arc_from_to(P[p], t, net)
        for p in post:
            petri_utils.add_arc_from_to(t, P[p], net)

    tr("open", "open", ["source"], ["p_rev", "p_ai", "p_ci", "p_watch"])
    # "Review" subprocess
    tr("assign", None, ["p_rev"], ["p_insp"])
    tr("v_approve", "rev_approve", ["p_insp"], ["p_rev_done"])
    tr("v_changes", "rev_changes", ["p_insp"], ["p_rework"])
    tr("v_comment", "rev_comment", ["p_insp"], ["p_insp"])
    tr("rework", "revision", ["p_rework"], ["p_insp"])
    if relaxed:  # transition 11: reviews and revisions after the first approval
        tr("post_approve", "rev_approve", ["p_rev_done"], ["p_rev_done"])
        tr("post_changes", "rev_changes", ["p_rev_done"], ["p_rev_done"])
        tr("post_comment", "rev_comment", ["p_rev_done"], ["p_rev_done"])
        tr("post_revision", "revision", ["p_rev_done"], ["p_rev_done"])
    # assistant branch: conditional, with repeated runs
    tr("ai_no", None, ["p_ai"], ["p_ai_end"])
    tr("ai_yes", None, ["p_ai"], ["p_ai_run"])
    tr("ai_run", "ai", ["p_ai_run"], ["p_ai_done"])
    tr("ai_again", None, ["p_ai_done"], ["p_ai_run"])
    tr("ai_done", None, ["p_ai_done"], ["p_ai_end"])
    # CI service
    tr("ci_run", None, ["p_ci"], ["p_ci_gw"])
    tr("ci_fail", None, ["p_ci_gw"], ["p_fix"])
    tr("ci_fix", "revision", ["p_fix"], ["p_ci"])
    tr("ci_pass", None, ["p_ci_gw"], ["p_ci_ok"])
    # staleness watch (a single active instance)
    tr("timer", "timer", ["p_watch"], ["p_stale"])
    tr("resume", None, ["p_stale"], ["p_watch"])
    # join, merge, end of the instance
    tr("merge", "merge", ["p_rev_done", "p_ci_ok"], ["p_merged"])
    tr("end", None, ["p_merged", "p_ai_end", "p_watch"], ["sink"])
    im, fm = Marking(), Marking()
    im[P["source"]] = 1
    fm[P["sink"]] = 1
    return net, im, fm


# ── alignments and summaries ────────────────────────────────────────────────

def deviations(trace_acts, alignment):
    """Log moves and model moves by event type. A log move of a review or revision is
    marked after_approval if an "approve" review occurs earlier in the trace
    (for rev_approve: if the trace has another approval, because the alignment may
    skip either of two equivalent approvals)."""
    log_moves, model_moves = Counter(), Counter()
    n_appr = sum(1 for a in trace_acts if a == "rev_approve")
    i = 0
    seen_appr = False
    for lg, md in alignment:
        if lg != ">>":
            act = trace_acts[i]
            if md == ">>":
                after = (n_appr >= 2) if act == "rev_approve" else seen_appr
                log_moves[(act, "after_approval" if after else "before_approval")] += 1
            if act == "rev_approve":
                seen_appr = True
            i += 1
        elif md is not None:
            model_moves[md] += 1
    return log_moves, model_moves


CAT_NAMES = {"a": "rev_changes або rev_comment після першого схвалення",
             "b": "rev_approve після доопрацювання після схвалення",
             "c": "злиття без схвалення людиною (автомат станів відкидає)",
             "e": "запит змін без ревізії до наступного вердикту",
             "d": "інші"}
CATS = "abced"


def classify_moves(acts, alignment):
    """[(category, detail)] for every log move and visible model move of a trace;
    the first value says whether there is a human approval before the merge.

    Among several equal-cost alignments one is chosen arbitrarily, and it often
    "bypasses" reviews after an approval by moving the approval (and the merge) past
    them: a log move rev_approve/merge plus a model move rev_approve/merge cost less
    than several log moves of comments. So the category is set by the trace context,
    not only by the event of the move:
      c  the trace has no human approval before the merge (all moves of the trace);
      a  a log move rev_changes/rev_comment after the first approval, or a
         rev_approve/merge move (log or model) if the trace has rev_changes/rev_comment
         after the first approval (detail displaced);
      b  a rev_approve move (log or model) in a trace with two or more approvals
         (after the filter, with a revision between them) unless it went to a by the
         log move; a log move rev_approve with two or more approvals is always b;
      e  a log move rev_changes before the first approval or a model move revision: in
         the net, rework is mandatory after a change request;
      d  the rest."""
    i_merge = acts.index("merge")
    approved = "rev_approve" in acts[:i_merge]
    n_appr = acts.count("rev_approve")
    fa = acts.index("rev_approve") if "rev_approve" in acts else None
    post_rev = fa is not None and any(a in ("rev_changes", "rev_comment") for a in acts[fa + 1:])
    out, i, seen_appr = [], 0, False

    def other(act, kind):
        if act == "rev_approve" and n_appr >= 2 and kind == "log":
            return "b", ""
        if act in ("rev_approve", "merge") and post_rev:
            return "a", ":displaced"
        if act == "rev_approve" and n_appr >= 2:
            return "b", ""
        if (kind == "log" and act == "rev_changes") or (kind == "model" and act == "revision"):
            return "e", ""
        return "d", ""

    for lg, md in alignment:
        if lg != ">>":
            act = acts[i]
            if md == ">>":
                ctx = ("after_merge" if i > i_merge else
                       "after_approval" if seen_appr else "before_approval")
                if not approved:
                    cat, sfx = "c", ""
                elif act in ("rev_changes", "rev_comment") and seen_appr:
                    cat, sfx = "a", ""
                else:
                    cat, sfx = other(act, "log")
                out.append((cat, f"log:{act}:{ctx}{sfx}"))
            if act == "rev_approve":
                seen_appr = True
            i += 1
        elif md is not None:
            cat, sfx = ("c", "") if not approved else other(md, "model")
            out.append((cat, f"model:{md}{sfx}"))
    return approved, out


def categorise(cases, res, replay_map, per_trace):
    """Deviation categories of non-fitting traces (variant main_noreapprove)."""
    moves, traces_with, detail = Counter(), Counter(), defaultdict(Counter)
    nonfit = explained = explained_e = 0
    agree = disagree = 0
    rej_cat_nonfit = Counter()
    for (cid, evs), r in zip(cases, res):
        acts = [a for _, a in evs]
        approved, mv = classify_moves(acts, r["alignment"])
        acc, rcat = replay_map[cid]
        if acc == int(approved):
            agree += 1
        else:
            disagree += 1
        if r["fitness"] == 1.0:
            continue
        nonfit += 1
        cats = {c for c, _ in mv}
        explained += int(bool(cats) and cats <= {"a", "b", "c"})
        explained_e += int(bool(cats) and cats <= {"a", "b", "c", "e"})
        if not approved:
            rej_cat_nonfit[rcat or "(accepted)"] += 1
        for c in cats:
            traces_with[c] += 1
        for c, d in mv:
            moves[c] += 1
            detail[c][d] += 1
        per_trace[cid]["nr_cats"] = "".join(sorted(cats))
    total = sum(moves.values())
    return {
        "names": CAT_NAMES,
        "nonfit_n": nonfit, "explained_n": explained,
        "explained_pct": 100.0 * explained / nonfit if nonfit else None,
        "explained_abce_n": explained_e,
        "explained_abce_pct": 100.0 * explained_e / nonfit if nonfit else None,
        "moves_total": total,
        "moves": {c: moves[c] for c in CATS},
        "moves_pct": {c: 100.0 * moves[c] / total if total else None for c in CATS},
        "traces_with": {c: traces_with[c] for c in CATS},
        "traces_with_pct": {c: 100.0 * traces_with[c] / nonfit if nonfit else None for c in CATS},
        "detail": {c: dict(detail[c].most_common()) for c in CATS},
        "replay_agree_n": agree, "replay_disagree_n": disagree,
        "c_reject_category": dict(rej_cat_nonfit.most_common()),
    }


def align(log, net, im, fm):
    res = pm4py.conformance_diagnostics_alignments(log, net, im, fm, multi_processing=False)
    return res


def summarise(res, repos_of_trace):
    fit = [r["fitness"] for r in res]
    by = defaultdict(lambda: {"n": 0, "fit_sum": 0.0, "n_fit": 0})
    for r, repo in zip(res, repos_of_trace):
        b = by[repo]
        b["n"] += 1
        b["fit_sum"] += r["fitness"]
        b["n_fit"] += int(r["fitness"] == 1.0)
    cost = sum(r["cost"] for r in res)
    bwc = sum(r["bwc"] for r in res)
    return {
        "n": len(res),
        "fitness": sum(fit) / len(fit),
        "fit_n": sum(1 for f in fit if f == 1.0),
        "fit_pct": 100.0 * sum(1 for f in fit if f == 1.0) / len(fit),
        "log_fitness": 1.0 - cost / bwc if bwc else None,
        "by_repo": {k: {"n": v["n"], "fitness": v["fit_sum"] / v["n"], "fit_n": v["n_fit"],
                        "fit_pct": 100.0 * v["n_fit"] / v["n"]} for k, v in sorted(by.items())},
    }


