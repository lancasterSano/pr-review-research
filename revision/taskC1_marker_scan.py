#!/usr/bin/env python3
"""Task C1 cross-check — find AI-review *text signatures* and group them by login.

The allowlist in taskC_common.py is built from account names. This script is the
independent check in the other direction: it searches every review body and every
review-thread comment body for signatures that only LLM review tools emit
(tool self-identification strings, HTML marker comments, branded headers), and
reports which logins produce them. Any login that emits such a signature but is
not on the allowlist is a miss; any allowlisted login that emits none is worth a
second look.

Also reports, per login, what fraction of that login's events carry an AI
signature — which is how mixed-purpose accounts (a single app account used for
both deployment previews and AI review) are detected.
"""

import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from taskC_common import iter_raw, classify_login  # noqa: E402

# Signatures. Each is a (name, compiled regex). They are intentionally specific:
# branded strings and machine-readable markers, not generic words like "AI".
SIGNATURES = [
    ("copilot_review", re.compile(r"Copilot (?:AI )?review|## Pull request overview|copilot-pull-request-reviewer", re.I)),
    ("coderabbit", re.compile(r"coderabbit|Walkthrough</summary>|Rate limit exceeded.*CodeRabbit", re.I)),
    ("codex", re.compile(r"Codex Review|chatgpt\.com/codex|About Codex in GitHub", re.I)),
    ("vercel_vade", re.compile(r"VADE-CATEGORY|VADE-RECOMMENDATION|VADE-GITHUB-SUGGESTION-ID", re.I)),
    ("graphite_diamond", re.compile(r"graphite\.dev/.*diamond|Diamond.*AI review|graphite-app", re.I)),
    ("greptile", re.compile(r"greptile", re.I)),
    ("cursor_bugbot", re.compile(r"bugbot|cursor\.com/bugbot|cursor\.com/agents", re.I)),
    ("devin", re.compile(r"devin\.ai|app\.devin\.ai", re.I)),
    ("gemini_code_assist", re.compile(r"gemini-code-assist|Gemini Code Assist", re.I)),
    ("claude_code", re.compile(r"claude\.ai/code|Generated with \[?Claude Code|anthropic\.com/claude-code", re.I)),
    ("diffray", re.compile(r"diffray\.ai", re.I)),
    ("sourcery", re.compile(r"sourcery\.ai", re.I)),
    ("qodo", re.compile(r"qodo|codiumai|PR-Agent", re.I)),
    ("ellipsis", re.compile(r"ellipsis\.dev", re.I)),
    ("korbit", re.compile(r"korbit\.ai", re.I)),
    ("codeant", re.compile(r"codeant\.ai", re.I)),
    ("generic_ai_disclaimer", re.compile(
        r"(this (?:review|comment) (?:was|is) (?:auto)?generated by|"
        r"AI-generated review|automated review suggestions|"
        r"I'm an AI|as an AI (?:assistant|reviewer))", re.I)),
]


def main():
    hits = defaultdict(lambda: defaultdict(int))   # login -> sig -> n events
    events = defaultdict(int)                       # login -> n events total
    any_sig = defaultdict(int)                      # login -> n events with >=1 sig

    for pr_type in ("merged", "open"):
        for repo, pr in iter_raw(pr_type):
            bodies = []
            for r in pr.get("reviews", {}).get("nodes", []) or []:
                a = (r.get("author") or {}).get("login")
                if a:
                    bodies.append((a, r.get("body") or ""))
            for t in pr.get("reviewThreads", {}).get("nodes", []) or []:
                for c in (t.get("comments", {}) or {}).get("nodes", []) or []:
                    a = (c.get("author") or {}).get("login")
                    if a:
                        bodies.append((a, c.get("body") or ""))
            for login, body in bodies:
                events[login] += 1
                if not body:
                    continue
                found = False
                for name, rx in SIGNATURES:
                    if rx.search(body):
                        hits[login][name] += 1
                        found = True
                if found:
                    any_sig[login] += 1

    rows = []
    for login, n_sig in any_sig.items():
        rows.append((login, events[login], n_sig, n_sig / events[login],
                     dict(hits[login]), classify_login(login)))
    rows.sort(key=lambda r: -r[2])

    print(f"{'login':34s} {'events':>8} {'sig_ev':>8} {'frac':>6}  class")
    print("-" * 100)
    for login, ev, ns, frac, sig, cls in rows:
        if ns < 3:
            continue
        top = sorted(sig.items(), key=lambda x: -x[1])[:4]
        print(f"{login[:34]:34s} {ev:>8} {ns:>8} {frac:>6.3f}  {cls:13s} "
              + ", ".join(f"{k}={v}" for k, v in top))

    print("\n### Logins with AI signatures NOT on the AI allowlist (potential misses)")
    for login, ev, ns, frac, sig, cls in rows:
        if cls != "ai_assistant" and ns >= 3:
            top = sorted(sig.items(), key=lambda x: -x[1])[:4]
            print(f"  {login:34s} events={ev:>7} sig={ns:>7} frac={frac:.3f} class={cls} "
                  + ", ".join(f"{k}={v}" for k, v in top))

    print("\n### Allowlisted AI logins and their signature coverage")
    for login, ev in sorted(events.items(), key=lambda x: -x[1]):
        if classify_login(login) == "ai_assistant":
            ns = any_sig.get(login, 0)
            print(f"  {login:34s} events={ev:>7} with_signature={ns:>7} ({ns / ev:.3f})")


if __name__ == "__main__":
    main()
